#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Generate per-tenant shortcut workflows that dispatch consolidated workflows
// with fixed inputs (GitHub UI cannot prefill workflow_dispatch via URL).
//
// Usage: node scripts/generate-tenant-shortcuts.mjs
// ---------------------------------------------------------------------------

import { execFileSync } from "child_process";
import { readdirSync, mkdirSync, rmSync, existsSync, promises as fsPromises } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
import { loadRegistry } from "./tenant-registry.mjs";

export const OFFBOARD_CONFIRM_SHELL = `
if [ "$CONFIRM" != "offboard" ]; then
  echo "ERROR: type offboard exactly to confirm decommissioning"
  exit 1
fi
`.trim();

/** Same gate as generated offboard shortcut validate jobs (for tests). */
export function validateOffboardConfirm(confirm) {
  try {
    execFileSync("sh", ["-c", OFFBOARD_CONFIRM_SHELL], {
      env: { ...process.env, CONFIRM: confirm },
      stdio: "ignore",
    });
    return true;
  } catch {
    return false;
  }
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const workflowsDir = join(root, ".github/workflows");

const GENERATED_HEADER = `# GENERATED — do not edit. Regenerated by scripts/generate-tenant-shortcuts.mjs`;
const GENERATED_SHORTCUT = /^isc-(backup|toggle|verify|offboard)-.+\.yml$/;

function isGeneratedShortcutFile(name) {
  return GENERATED_SHORTCUT.test(name);
}

function dispatchWrapper({ name, targetWorkflow, inputs }) {
  const inputsJson = JSON.stringify(inputs);
  return `${GENERATED_HEADER}
name: "${name}"

on:
  workflow_dispatch:

permissions:
  contents: read
  actions: write

jobs:
  dispatch:
    runs-on: ubuntu-latest
    steps:
      - name: Dispatch ${targetWorkflow}
        uses: actions/github-script@v7
        with:
          script: |
            const inputs = ${inputsJson};
            await github.rest.actions.createWorkflowDispatch({
              owner: context.repo.owner,
              repo: context.repo.repo,
              workflow_id: "${targetWorkflow}",
              ref: context.ref,
              inputs,
            });
            core.info(\`Dispatched ${targetWorkflow} with \${JSON.stringify(inputs)}\`);
`;
}

function offboardDispatchWrapper({ tenant }) {
  const inputsJson = JSON.stringify({
    operation: "offboard",
    tenant,
    confirm_tenant: tenant,
  });
  return `${GENERATED_HEADER}
name: "ISC Offboard — ${tenant}"

on:
  workflow_dispatch:
    inputs:
      confirm:
        description: 'Type "offboard" to confirm decommissioning ${tenant}'
        required: true
        type: string

permissions:
  contents: read
  actions: write

jobs:
  validate:
    runs-on: ubuntu-latest
    steps:
      - name: Confirm offboard intent
        env:
          CONFIRM: \${{ inputs.confirm }}
        run: |
          ${OFFBOARD_CONFIRM_SHELL.split("\n").join("\n          ")}

  dispatch:
    needs: validate
    runs-on: ubuntu-latest
    steps:
      - name: Dispatch isc-lifecycle.yml
        uses: actions/github-script@v7
        with:
          script: |
            const inputs = ${inputsJson};
            await github.rest.actions.createWorkflowDispatch({
              owner: context.repo.owner,
              repo: context.repo.repo,
              workflow_id: "isc-lifecycle.yml",
              ref: context.ref,
              inputs,
            });
            core.info(\`Dispatched isc-lifecycle.yml with \${JSON.stringify(inputs)}\`);
`;
}

export async function generateTenantShortcutWorkflows(registry, options = {}) {
  const dir = options.workflowsDir ?? workflowsDir;
  const tenants = registry.tenants?.map((t) => t.name) ?? [];

  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }

  for (const file of readdirSync(dir)) {
    if (isGeneratedShortcutFile(file)) rmSync(join(dir, file));
  }

  const files = [];
  const promises = [];
  for (const tenant of tenants) {
    const backupFile = `isc-backup-${tenant}.yml`;
    promises.push(
      fsPromises.writeFile(
        join(dir, backupFile),
        dispatchWrapper({
          name: `ISC Backup — ${tenant}`,
          targetWorkflow: "isc-backup.yml",
          inputs: { tenant },
        })
      )
    );
    files.push(backupFile);

    const toggleFile = `isc-toggle-${tenant}.yml`;
    promises.push(
      fsPromises.writeFile(
        join(dir, toggleFile),
        dispatchWrapper({
          name: `ISC Toggle schedule — ${tenant}`,
          targetWorkflow: "isc-lifecycle.yml",
          inputs: { operation: "schedule-toggle", tenant },
        })
      )
    );
    files.push(toggleFile);

    const verifyFile = `isc-verify-${tenant}.yml`;
    promises.push(
      fsPromises.writeFile(
        join(dir, verifyFile),
        dispatchWrapper({
          name: `ISC Verify — ${tenant}`,
          targetWorkflow: "isc-lifecycle.yml",
          inputs: { operation: "verify", tenant },
        })
      )
    );
    files.push(verifyFile);

    const offboardFile = `isc-offboard-${tenant}.yml`;
    promises.push(
      fsPromises.writeFile(
        join(dir, offboardFile),
        offboardDispatchWrapper({ tenant })
      )
    );
    files.push(offboardFile);
  }

  await Promise.all(promises);

  return { dir, files, tenants };
}

export function tenantShortcutWorkflowFile(tenant, kind) {
  if (kind === "backup") return `isc-backup-${tenant}.yml`;
  if (kind === "toggle") return `isc-toggle-${tenant}.yml`;
  if (kind === "verify") return `isc-verify-${tenant}.yml`;
  if (kind === "offboard") return `isc-offboard-${tenant}.yml`;
  throw new Error(`Unknown shortcut kind: ${kind}`);
}

export function workflowDispatchUrl(repoSlug, workflowPath) {
  const normalized = workflowPath.replace(/^\.github\/workflows\//, "");
  return `https://github.com/${repoSlug}/actions/workflows/${normalized}`;
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url);
if (isMain) {
  const registry = loadRegistry();
  const { files } = await generateTenantShortcutWorkflows(registry);
  console.log(`Generated ${files.length} shortcut workflow(s) in .github/workflows/`);
}
